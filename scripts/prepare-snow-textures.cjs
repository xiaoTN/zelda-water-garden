const fs=require('fs'),path=require('path'),{execFileSync}=require('child_process');
const root=path.resolve(__dirname,'..'),source=path.join(root,'assets-source/snow001');
fs.mkdirSync(path.join(root,'tmp'),{recursive:true});
const maps=['Color','NormalGL'].map(kind=>{
 const output=path.join(root,'tmp/snow-'+kind+'.jpg');
 execFileSync('ffmpeg',['-hide_banner','-loglevel','error','-y','-i',path.join(source,'Snow001_1K-JPG_'+kind+'.jpg'),'-vf','scale=512:512:flags=lanczos','-q:v','5',output],{windowsHide:true});
 const bytes=fs.readFileSync(output);if(bytes.length>102400)throw new Error('Snow map exceeds 100 KiB inline budget');
 console.log(kind+': '+bytes.length+' bytes at 512x512');
 return 'data:image/jpeg;base64,'+bytes.toString('base64');
});
fs.writeFileSync(path.join(root,'src/snow-textures.js'),'// ambientCG Snow001, CC0. Generated by scripts/prepare-snow-textures.cjs.\n// Embedded small images keep WebGL uploads origin-clean for offline file URLs.\nwindow.SnowTextures='+JSON.stringify(maps)+';\n');
